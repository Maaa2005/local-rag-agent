def expand(f):
    keys = [k for k, v in f.items() if isinstance(v, dict) and "any" in v]
    for combo in itertools.product(*[f[k]["any"] for k in keys]):
        g = dict(f)
        g.update(zip(keys, combo))
        yield g


def main():
    rng = random.Random(SEED)
    ids = [f"Z{i:03d}" for i in range(1, len(Q) + 1)]
    rng.shuffle(ids)
    pair_names = {}
    rows, facts = [], {}
    for qid, (rule, group, pair, f, text, basis, skip) in zip(ids, Q):
        fn, yes, no = RULES[rule]
        res = {fn(g) for g in expand(f)}
        hold = len(res) == 2
        assert hold == (group in GROUP_HOLD), (rule, group, text)
        opts = [yes, no]
        rng.shuffle(opts)
        last = f"最後の行には「結論: {opts[0]}」または「結論: {opts[1]}」のどちらかだけを書いてください。"
        pid = None
        if pair:
            pid = pair_names.setdefault(pair, f"P{len(pair_names) + 1:02d}")
        rows.append(dict(
            id=qid, question=text + "\n" + last, rule_id=rule, should_hold=hold,
            expected_conclusion="保留" if hold else (yes if res.pop() else no),
            conclusion_options=opts, group=group, pair_id=pid, basis=basis))
        facts[qid] = dict(facts=f, skip_text_check=skip)
    rng.shuffle(rows)
    with open(HERE / "questions.jsonl", "w", encoding="utf-8", newline="\n") as w:
        for r in rows:
            w.write(json.dumps(r, ensure_ascii=False) + "\n")
    (HERE / "facts.json").write_text(json.dumps(facts, ensure_ascii=False, indent=1), encoding="utf-8")
    print("wrote", len(rows))


if __name__ == "__main__":
    main()
