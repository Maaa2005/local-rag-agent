def fiscal_start(x):
    y = x.year if x.month >= 4 else x.year - 1
    return date(y, 4, 1)


def exam(f):
    if not f["regular"]:
        return False
    pd, ad = d(f["pass_date"]), d(f["apply_date"])
    if not pd < ad <= pd + timedelta(days=90):
        return False
    if f["required"]:
        return True
    fs = fiscal_start(pd)
    total = f["fee"] + sum(a for dt, a in f["prior"] if fiscal_start(d(dt)) == fs)
    return total <= 60000


def in_busy(x):
    md = (x.month, x.day)
    return (7, 20) <= md <= (8, 31) or md >= (12, 28) or md <= (1, 3)


def resort(f):
    if not f["accompany"]:
        return False
    ci, ap = d(f["checkin"]), d(f["apply"])
    if ap > ci - timedelta(days=7):
        return False
    limit = 4
    if in_busy(ci):
        award = f["award"]
        ok = award is not None and d(award) <= ci <= d(award).replace(year=d(award).year + 1)
        limit = 4 if ok else 2
    return f["nights"] <= limit


def mycar(f):
    if not f["probation_done"]:
        return False
    if f["coverage_man"] < 3000:
        return False
    return f["handicap"] or f["dist_m"] >= 2000


def circle(f):
    if not f["registered"]:
        return False
    need = 3 if (f["month"] == 4 and f["welcome"]) else 5
    if f["minutes"] < 90 or f["members"] < need:
        return False
    return min(f["cost"] * 50 // 100, f["members"] * 1000) >= 3000


def months_between(a, b):
    m = (b.year - a.year) * 12 + (b.month - a.month)
    return m - 1 if b.day < a.day else m


def refresh(f):
    if not f["regular"] or f["days_before"] < 14:
        return False
    return months_between(d(f["hire"]), fiscal_start(d(f["start"]))) + f["transfer_months"] >= 120


