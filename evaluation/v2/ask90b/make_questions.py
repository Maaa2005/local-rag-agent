def main():
    rng = random.Random(SEED)
    entries = list(ENTRIES)
    rng.shuffle(entries)
    questions, facts = [], []
    for i, e in enumerate(entries, 1):
        qid = f"B{i:03d}"
        opts = list(OPTIONS[e["rule"]])
        rng.shuffle(opts)
        tail = f"最後の行には「結論: {opts[0]}」または「結論: {opts[1]}」のどちらかだけを書いてください。"
        hold = e["kind"] == "dont_know"
        questions.append(dict(id=qid, question=e["text"] + "\n" + tail, rule_id=e["rule"], kind=e["kind"],
                              should_hold=hold, expected_conclusion=HOLD if hold else e["concl"],
                              conclusion_options=opts, group=e["kind"], pair_id=e["pair"], basis=e["basis"]))
        facts.append(dict(id=qid, facts=e["facts"], stated=e["stated"], unknowns=e["unknowns"]))
    order = sorted(range(len(questions)), key=lambda k: questions[k]["id"])
    for name, rows in (("questions.jsonl", questions), ("facts.jsonl", facts)):
        with open(HERE / name, "w", encoding="utf-8", newline="\n") as fh:
            for k in order:
                fh.write(json.dumps(rows[k], ensure_ascii=False) + "\n")
    print(f"wrote {len(questions)} scenes")


if __name__ == "__main__":
    main()
